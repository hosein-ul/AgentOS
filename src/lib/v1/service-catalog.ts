export type ServiceMethod = "GET" | "POST"
export type ServiceArea = "discovery" | "events" | "email" | "phone" | "domain"

export type ServiceCatalogEntry = {
  id: string
  area: ServiceArea
  method: ServiceMethod
  endpoint: string
  amount: string
  currency: "USDT"
  x402Price: string | null
  description: string
  authenticated: boolean
  paid: boolean
  startHere: boolean
  available: boolean
  registerOnOkx: boolean
  idempotency: "required" | "recommended" | "not-applicable"
  requiredInput: Record<string, string>
  optionalInput: Record<string, string>
  output: string
  mainErrors: string[]
  nextServiceId: string | null
  guide: string
}

function paid(
  entry: Omit<ServiceCatalogEntry, "paid" | "x402Price" | "available" | "registerOnOkx" | "idempotency">,
): ServiceCatalogEntry & { paid: true; x402Price: string } {
  return {
    ...entry,
    paid: true,
    x402Price: `$${entry.amount}`,
    available: true,
    registerOnOkx: true,
    idempotency: "required",
  }
}

function free(
  entry: Omit<ServiceCatalogEntry, "paid" | "x402Price" | "available" | "registerOnOkx" | "idempotency">,
): ServiceCatalogEntry & { paid: false; x402Price: null } {
  return {
    ...entry,
    paid: false,
    x402Price: null,
    available: true,
    registerOnOkx: false,
    idempotency: entry.method === "POST" ? "recommended" : "not-applicable",
  }
}

