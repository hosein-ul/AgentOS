export function getServiceById(serviceId: string) {
  return SERVICE_CATALOG.find((service) => service.id === serviceId) ?? null
}

export function getServiceByEndpoint(endpoint: string, method: ServiceMethod = "POST") {
  return SERVICE_CATALOG.find((service) => service.endpoint === endpoint && service.method === method) ?? null
}

export function isStartHereEndpoint(endpoint: string) {
  return SERVICE_CATALOG.some((service) => service.endpoint === endpoint && service.startHere && service.available)
}
